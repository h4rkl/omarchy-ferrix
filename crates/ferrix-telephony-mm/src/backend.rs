//! The ModemManager `ModemBackend` over the system bus (feature
//! `production`).
//!
//! One blocking D-Bus connection serves both directions: proxies for
//! commands and property reads, and a watcher thread that consumes the
//! connection's message stream after subscribing to the signals that matter
//! (`NameOwnerChanged` for ModemManager itself, `InterfacesAdded/Removed`
//! for modems, `Modem.StateChanged`, `PropertiesChanged`, `Voice.CallAdded/
//! CallDeleted`, `Call.StateChanged`, `Messaging.Added`). A second thread
//! emits `Tick` once a second from a monotonic clock; that is the only place
//! this adapter reads time, and it is a production adapter, so wall-clock
//! progress is the intended behaviour.
//!
//! The cached [`BackendSnapshot`] is refreshed from D-Bus by the watcher and
//! served from memory, so `snapshot()` never blocks the daemon on the bus.
//!
//! Untested on this host: no ModemManager instance exists here. The mapping
//! functions are tested in [`crate::mapping`]; this module is type-checked.

