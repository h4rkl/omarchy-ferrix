#[derive(Clone, Debug)]
struct TrackedCall {
    direction: Direction,
    number: E164,
    state: CallState,
    local_hangup: bool,
}

struct Inner {
    modem_path: Option<OwnedObjectPath>,
    has_voice: bool,
    has_messaging: bool,
    /// Whether the current modem exports ModemManager's standard
    /// `Modem.Simple` packet-data interface.
    has_simple: bool,
    /// Whether the selected plugin rejects a data request without an APN.
    requires_apn: bool,
    /// Data bearer created by this adapter.  ModemManager may expose other
    /// bearers (for example IMS or tethering); disconnecting those would be a
    /// destructive cross-service side effect.
    owned_data_bearer: Option<OwnedObjectPath>,
    snapshot: BackendSnapshot,
    /// Keyed by object path string (`OwnedObjectPath` is not `Ord`).
    calls: BTreeMap<String, TrackedCall>,
    /// Outgoing messages we created, by object path.
    outgoing_sms: BTreeSet<String>,
    /// Inbound messages already published (ModemManager keeps them stored).
    seen_sms: BTreeSet<String>,
    sinks: Vec<Sender<BackendEvent>>,
    started: Instant,
}

fn lock<T>(mutex: &Mutex<T>) -> MutexGuard<'_, T> {
    mutex
        .lock()
        .unwrap_or_else(|poisoned| poisoned.into_inner())
}

fn bus_error(error: zbus::Error) -> BackendError {
    BackendError::backend(format!("d-bus: {error}"))
}

/// ModemManager-backed [`ModemBackend`].
pub struct ModemManagerBackend {
    connection: Connection,
    inner: Arc<Mutex<Inner>>,
}

impl ModemManagerBackend {
    /// Connects to the system bus, adopts the first modem ModemManager
    /// exports (or reports `absent`), subscribes to signals, and starts the
    /// watcher and tick threads.
    pub fn connect() -> Result<Self, String> {
        let connection = Connection::system().map_err(|e| format!("system bus: {e}"))?;
        let inner = Arc::new(Mutex::new(Inner {
            modem_path: None,
            has_voice: false,
            has_messaging: false,
            has_simple: false,
            requires_apn: false,
            owned_data_bearer: None,
            snapshot: BackendSnapshot {
                audio: AudioRouteState {
                    active: AudioRoute::Earpiece,
                    available: Default::default(),
                },
                ..BackendSnapshot::default()
            },
            calls: BTreeMap::new(),
            outgoing_sms: BTreeSet::new(),
            seen_sms: BTreeSet::new(),
            sinks: Vec::new(),
            started: Instant::now(),
        }));
        let backend = Self { connection, inner };
        backend
            .subscribe_signals()
            .map_err(|e| format!("d-bus match rules: {e}"))?;
        backend.enumerate();
        backend.spawn_watcher();
        backend.spawn_ticker();
        Ok(backend)
    }

    fn subscribe_signals(&self) -> zbus::Result<()> {
        let dbus = DBusProxy::new(&self.connection)?;
        let rules = [
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .interface("org.freedesktop.DBus")?
                .member("NameOwnerChanged")?
                .arg(0, MM_SERVICE)?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_OBJECT_MANAGER)?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_MODEM)?
                .member("StateChanged")?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_PROPERTIES)?
                .member("PropertiesChanged")?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_VOICE)?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_CALL)?
                .member("StateChanged")?
                .build(),
            MatchRule::builder()
                .msg_type(MessageType::Signal)
                .sender(MM_SERVICE)?
                .interface(IFACE_MESSAGING)?
                .build(),
        ];
        for rule in rules {
            dbus.add_match_rule(rule)?;
        }
        Ok(())
    }

    fn emit(&self, event: BackendEvent) {
        lock(&self.inner)
            .sinks
            .retain(|sink| sink.send(event.clone()).is_ok());
    }

    fn now_ms(&self) -> u64 {
        u64::try_from(lock(&self.inner).started.elapsed().as_millis()).unwrap_or(u64::MAX)
    }

    /// Reads the object tree and adopts the first modem.
    fn enumerate(&self) {
        let objects = ObjectManagerProxyBlocking::new(&self.connection)
            .and_then(|p| p.get_managed_objects())
            .unwrap_or_default();
        let mut modem: Option<(OwnedObjectPath, bool, bool, bool)> = None;
        for (path, interfaces) in objects {
            if interfaces.contains_key(IFACE_MODEM) {
                let voice = interfaces.contains_key(IFACE_VOICE);
                let messaging = interfaces.contains_key(IFACE_MESSAGING);
                let simple = interfaces.contains_key(IFACE_SIMPLE);
                if modem
                    .as_ref()
                    .is_none_or(|(p, _, _, _)| path.as_str() < p.as_str())
                {
                    modem = Some((path, voice, messaging, simple));
                }
            }
        }
        match modem {
            Some((path, voice, messaging, simple)) => self.adopt(path, voice, messaging, simple),
            None => self.drop_modem(),
        }
    }

    fn adopt(&self, path: OwnedObjectPath, has_voice: bool, has_messaging: bool, has_simple: bool) {
        let plugin = ModemProxyBlocking::builder(&self.connection)
            .path(path.clone())
            .ok()
            .and_then(|builder| builder.build().ok())
            .and_then(|modem| modem.plugin().ok());
        let is_samsung_sit = is_samsung_sit_plugin(plugin.as_deref());
        {
            let mut inner = lock(&self.inner);
            let modem_changed = inner.modem_path.as_ref() != Some(&path);
            inner.modem_path = Some(path.clone());
            inner.has_voice = has_voice;
            inner.has_messaging = has_messaging;
            inner.has_simple = has_simple;
            inner.requires_apn = is_samsung_sit;
            // A new modem object has a new bearer namespace.  Never carry a
            // path from a removed/replaced modem into the new instance.
            if modem_changed {
                inner.owned_data_bearer = None;
            }
            inner.snapshot.capabilities =
                mapping::capabilities(has_voice, has_messaging, has_simple, !is_samsung_sit);
        }
        self.refresh_modem();
        self.refresh_calls();
        // `connect()` enumerates before the daemon has a chance to subscribe.
        // Replaying here unconditionally would mark stored SMS as seen and
        // then drop the events because there are no sinks yet.  A restart,
        // on the other hand, reaches this path with existing subscribers and
        // must replay the modem's stored messages.
        self.replay_inbound_sms_if_subscribed();
    }

    fn drop_modem(&self) {
        let mut inner = lock(&self.inner);
        inner.modem_path = None;
        inner.has_voice = false;
        inner.has_messaging = false;
        inner.has_simple = false;
        inner.requires_apn = false;
        inner.owned_data_bearer = None;
        inner.snapshot = BackendSnapshot {
            now_ms: inner.snapshot.now_ms,
            ..BackendSnapshot::default()
        };
        inner.calls.clear();
        // Object paths are owned by the current ModemManager instance.  Do
        // not carry deduplication or outgoing-message state across a modem
        // removal/restart: a replacement instance may reuse the same paths,
        // and stale entries would suppress valid inbound SMS or misclassify
        // a new message as one of the old outgoing messages.
        inner.outgoing_sms.clear();
        inner.seen_sms.clear();
    }

    fn modem_path(&self) -> Result<OwnedObjectPath, BackendError> {
        lock(&self.inner)
            .modem_path
            .clone()
            .ok_or(BackendError::NoModem)
    }

    fn modem_proxy(&self) -> Result<ModemProxyBlocking<'_>, BackendError> {
        let path = self.modem_path()?;
        ModemProxyBlocking::builder(&self.connection)
            .path(path)
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    fn bearer_proxy(
        &self,
        path: &OwnedObjectPath,
    ) -> Result<BearerProxyBlocking<'_>, BackendError> {
        BearerProxyBlocking::builder(&self.connection)
            .path(path.clone())
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    fn simple_proxy(&self) -> Result<SimpleProxyBlocking<'_>, BackendError> {
        if !lock(&self.inner).has_simple {
            return Err(BackendError::Unsupported(TelephonyFeature::Data));
        }
        let path = self.modem_path()?;
        SimpleProxyBlocking::builder(&self.connection)
            .path(path)
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    /// Observes ModemManager's standard packet-data bearer state without
    /// opening a CPIF node or trying to infer the S5300 command protocol.
    fn data_bearer(&self, modem: &ModemProxyBlocking<'_>, modem_state: i32) -> DataBearer {
        if !lock(&self.inner).has_simple {
            return mapping::data_bearer(false, modem_state, false, None);
        }
        let paths = match modem.bearers() {
            Ok(paths) => paths,
            Err(error) => {
                return DataBearer::Failed {
                    reason: format!("ModemManager bearer enumeration failed: {error}"),
                };
            }
        };
        for path in paths {
            let Ok(bearer) = self.bearer_proxy(&path) else {
                continue;
            };
            if bearer.connected().unwrap_or(false) {
                let interface = bearer.interface().ok();
                return mapping::data_bearer(true, modem_state, true, interface.as_deref());
            }
        }
        mapping::data_bearer(true, modem_state, false, None)
    }

    /// Re-reads modem, SIM, registration, signal, and power; emits deltas.
    fn refresh_modem(&self) {
        let Ok(modem) = self.modem_proxy() else {
            return;
        };
        let state = modem.state().unwrap_or(mapping::modem_state::UNKNOWN);
        let failed = modem.state_failed_reason().unwrap_or(0);
        let unlock = modem.unlock_required().unwrap_or(mapping::lock::UNKNOWN);
        let retries = modem
            .unlock_retries()
            .ok()
            .and_then(|map| map.get(&unlock).copied());
        let has_sim = modem.sim().map(|p| p.as_str() != "/").unwrap_or(false);
        let (quality, _) = modem.signal_quality().unwrap_or((0, false));
        let access_bits = modem.access_technologies().unwrap_or(0);
        let power = modem.power_state().unwrap_or(mapping::power_state::UNKNOWN);

        let path = modem.inner().path().to_owned();
        let (registration, operator) = ModemProxyBlocking::builder(&self.connection)
            .path(path.clone())
            .ok()
            .and_then(|b| {
                Modem3gppProxyBlocking::builder(&self.connection)
                    .path(path)
                    .ok()
                    .and(Some(b))
            })
            .and_then(|_| {
                Modem3gppProxyBlocking::builder(&self.connection)
                    .path(modem.inner().path().to_owned())
                    .ok()?
                    .build()
                    .ok()
            })
            .map(|p| {
                let registration = mapping::registration(p.registration_state().unwrap_or(0));
                let operator = mapping::operator(
                    &p.operator_name().unwrap_or_default(),
                    &p.operator_code().unwrap_or_default(),
                );
                (registration, operator)
            })
            .unwrap_or((ferrix_telephony_api::Registration::Unknown, None));

        let modem_state = mapping::modem_state(state, failed);
        let sim_state = mapping::sim_state(has_sim, unlock, retries, state, failed);
        let signal = mapping::signal(quality);
        let access = mapping::access_technology(access_bits);
        let radio = mapping::radio_power(power);
        let data = self.data_bearer(&modem, state);

        let mut events = Vec::new();
        {
            let mut inner = lock(&self.inner);
            let s = &mut inner.snapshot;
            if s.modem != modem_state {
                s.modem = modem_state.clone();
                events.push(BackendEvent::Modem(modem_state));
            }
            if s.sim != sim_state {
                s.sim = sim_state.clone();
                events.push(BackendEvent::Sim(sim_state));
            }
            if s.registration != registration || s.operator != operator || s.access != access {
                s.registration = registration;
                s.operator = operator.clone();
                s.access = access;
                events.push(BackendEvent::Registration {
                    registration,
                    operator,
                    access,
                });
            }
            if s.signal != signal {
                s.signal = signal;
                events.push(BackendEvent::Signal(signal));
            }
            if s.radio != radio {
                s.radio = radio;
                events.push(BackendEvent::Radio(radio));
            }
            if s.data != data {
                s.data = data.clone();
                events.push(BackendEvent::Data(data));
            }
        }
        for event in events {
            self.emit(event);
        }
    }

    fn call_proxy(&self, path: &OwnedObjectPath) -> Result<CallProxyBlocking<'_>, BackendError> {
        CallProxyBlocking::builder(&self.connection)
            .path(path.clone())
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    fn voice_proxy(&self) -> Result<VoiceProxyBlocking<'_>, BackendError> {
        if !lock(&self.inner).has_voice {
            return Err(BackendError::Unsupported(TelephonyFeature::Voice));
        }
        let path = self.modem_path()?;
        VoiceProxyBlocking::builder(&self.connection)
            .path(path)
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    fn messaging_proxy(&self) -> Result<MessagingProxyBlocking<'_>, BackendError> {
        if !lock(&self.inner).has_messaging {
            return Err(BackendError::Unsupported(TelephonyFeature::Sms));
        }
        let path = self.modem_path()?;
        MessagingProxyBlocking::builder(&self.connection)
            .path(path)
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    fn sms_proxy(&self, path: &OwnedObjectPath) -> Result<SmsProxyBlocking<'_>, BackendError> {
        SmsProxyBlocking::builder(&self.connection)
            .path(path.clone())
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)
    }

    /// Adopts every call ModemManager currently exports.
    fn refresh_calls(&self) {
        let Ok(voice) = self.voice_proxy() else {
            return;
        };
        for path in voice.calls().unwrap_or_default() {
            self.call_added(path);
        }
    }

    fn call_added(&self, path: OwnedObjectPath) {
        if lock(&self.inner).calls.contains_key(path.as_str()) {
            return;
        }
        let Ok(call) = self.call_proxy(&path) else {
            return;
        };
        let Some(direction) = mapping::call_direction(call.direction().unwrap_or(0)) else {
            return;
        };
        let Ok(number) = E164::new(normalize_number(&call.number().unwrap_or_default())) else {
            // A call without a usable number is still a call; use a
            // placeholder that cannot collide with a real subscriber.
            self.track_call(path, direction, E164::new("+00000000").ok(), &call);
            return;
        };
        self.track_call(path, direction, Some(number), &call);
    }

    fn track_call(
        &self,
        path: OwnedObjectPath,
        direction: Direction,
        number: Option<E164>,
        call: &CallProxyBlocking<'_>,
    ) {
        let Some(number) = number else {
            return;
        };
        let state = mapping::call_state(call.state().unwrap_or(0), direction);
        {
            let mut inner = lock(&self.inner);
            inner.calls.insert(
                path.to_string(),
                TrackedCall {
                    direction,
                    number: number.clone(),
                    state,
                    local_hangup: false,
                },
            );
            inner.snapshot.calls = inner
                .calls
                .iter()
                .map(|(p, c)| BackendCall {
                    handle: CallHandle(p.clone()),
                    direction: c.direction,
                    number: c.number.clone(),
                    state: c.state,
                    end_reason: None,
                })
                .collect();
        }
        self.emit(BackendEvent::CallAdded {
            handle: CallHandle(path.to_string()),
            direction,
            number,
            state,
        });
    }

    fn call_state_changed(&self, path: &OwnedObjectPath, new_state: i32, reason: u32) {
        let (direction, previous, local) = {
            let inner = lock(&self.inner);
            match inner.calls.get(path.as_str()) {
                Some(c) => (c.direction, c.state, c.local_hangup),
                None => return,
            }
        };
        let state = mapping::call_state(new_state, direction);
        if state == previous {
            return;
        }
        let end_reason = (state == CallState::Ended)
            .then(|| mapping::call_end_reason(reason, previous, direction, local));
        {
            let mut inner = lock(&self.inner);
            if let Some(c) = inner.calls.get_mut(path.as_str()) {
                c.state = state;
            }
            if let Some(c) = inner
                .snapshot
                .calls
                .iter_mut()
                .find(|c| c.handle.0 == path.as_str())
            {
                c.state = state;
                c.end_reason = end_reason.clone();
            }
        }
        self.emit(BackendEvent::CallChanged {
            handle: CallHandle(path.to_string()),
            state,
            end_reason,
        });
    }

    fn call_deleted(&self, path: &OwnedObjectPath) {
        let live = lock(&self.inner)
            .calls
            .get(path.as_str())
            .is_some_and(|c| c.state.is_live());
        if live {
            self.call_state_changed(
                path,
                mapping::call_state::TERMINATED,
                mapping::call_reason::TERMINATED,
            );
        }
        let mut inner = lock(&self.inner);
        inner.calls.remove(path.as_str());
        inner.snapshot.calls.retain(|c| c.handle.0 != path.as_str());
    }

    /// Publishes stored inbound messages not yet seen. ModemManager assembles
    /// concatenated messages itself, so every `received` object is complete.
    fn replay_inbound_sms(&self) {
        let Ok(messaging) = self.messaging_proxy() else {
            return;
        };
        for path in messaging.list().unwrap_or_default() {
            self.sms_added(path, true);
        }
    }

    fn replay_inbound_sms_if_subscribed(&self) {
        if !lock(&self.inner).sinks.is_empty() {
            self.replay_inbound_sms();
        }
    }

    fn sms_added(&self, path: OwnedObjectPath, received: bool) {
        if !received {
            return;
        }
        if lock(&self.inner).seen_sms.contains(path.as_str()) {
            return;
        }
        let Ok(sms) = self.sms_proxy(&path) else {
            return;
        };
        if !mapping::is_complete_inbound(sms.state().unwrap_or(0)) {
            return;
        }
        let Ok(from) = E164::new(normalize_number(&sms.number().unwrap_or_default())) else {
            return;
        };
        let body = sms.text().unwrap_or_default();
        lock(&self.inner).seen_sms.insert(path.to_string());
        self.emit(BackendEvent::SmsReceived { from, body });
    }

    fn sms_properties_changed(&self, path: &OwnedObjectPath) {
        let outgoing = lock(&self.inner).outgoing_sms.contains(path.as_str());
        if outgoing {
            let Ok(sms) = self.sms_proxy(path) else {
                return;
            };
            let (state, failure) = mapping::sms_state(
                sms.state().unwrap_or(0),
                sms.delivery_state()
                    .unwrap_or(mapping::delivery_state::UNKNOWN),
            );
            if matches!(
                state,
                ferrix_telephony_api::SmsState::Sent
                    | ferrix_telephony_api::SmsState::Delivered
                    | ferrix_telephony_api::SmsState::Failed
            ) {
                self.emit(BackendEvent::SmsChanged {
                    handle: SmsHandle(path.to_string()),
                    state,
                    failure,
                });
            }
        } else {
            // An inbound message finished receiving.
            self.sms_added(path.clone(), true);
        }
    }

    fn spawn_ticker(&self) {
        let inner = Arc::clone(&self.inner);
        thread::Builder::new()
            .name("ferrix-telephony-mm-tick".to_owned())
            .spawn(move || {
                loop {
                    thread::sleep(TICK_INTERVAL);
                    let now_ms = {
                        let mut guard = lock(&inner);
                        let now =
                            u64::try_from(guard.started.elapsed().as_millis()).unwrap_or(u64::MAX);
                        guard.snapshot.now_ms = now;
                        now
                    };
                    lock(&inner)
                        .sinks
                        .retain(|sink| sink.send(BackendEvent::Tick { now_ms }).is_ok());
                }
            })
            .expect("spawn tick thread");
    }

    fn spawn_watcher(&self) {
        let connection = self.connection.clone();
        let inner = Arc::clone(&self.inner);
        thread::Builder::new()
            .name("ferrix-telephony-mm-signals".to_owned())
            .spawn(move || {
                let backend = ModemManagerBackend { connection, inner };
                let stream = MessageIterator::from(backend.connection.clone());
                for message in stream.flatten() {
                    backend.handle_message(&message);
                }
                backend.emit(BackendEvent::BackendLost {
                    reason: "d-bus connection closed".to_owned(),
                });
            })
            .expect("spawn signal watcher");
    }

    fn handle_message(&self, message: &zbus::Message) {
        let header = message.header();
        if header.message_type() != MessageType::Signal {
            return;
        }
        let interface = header.interface().map(|i| i.as_str().to_owned());
        let member = header.member().map(|m| m.as_str().to_owned());
        let path = header.path().map(|p| OwnedObjectPath::from(p.to_owned()));
        let body = message.body();
        match (interface.as_deref(), member.as_deref()) {
            (Some("org.freedesktop.DBus"), Some("NameOwnerChanged")) => {
                if let Ok((name, _old, new)) = body.deserialize::<(String, String, String)>()
                    && name == MM_SERVICE
                {
                    if new.is_empty() {
                        self.drop_modem();
                        self.emit(BackendEvent::BackendLost {
                            reason: "modemmanager left the bus".to_owned(),
                        });
                    } else {
                        self.enumerate();
                        self.emit(BackendEvent::BackendRestarted);
                    }
                }
            }
            (Some(IFACE_OBJECT_MANAGER), Some("InterfacesAdded")) => {
                if let Ok((object, interfaces)) = body.deserialize::<(
                    OwnedObjectPath,
                    HashMap<String, HashMap<String, OwnedValue>>,
                )>() {
                    if interfaces.contains_key(IFACE_MODEM)
                        && lock(&self.inner).modem_path.is_none()
                    {
                        self.adopt(
                            object,
                            interfaces.contains_key(IFACE_VOICE),
                            interfaces.contains_key(IFACE_MESSAGING),
                            interfaces.contains_key(IFACE_SIMPLE),
                        );
                    } else if interfaces.contains_key(IFACE_BEARER)
                        && lock(&self.inner).modem_path.is_some()
                    {
                        // Bearer objects are children of the selected modem
                        // but do not carry the modem path in their signal. A
                        // fresh modem read folds their lifecycle into state.
                        self.refresh_modem();
                    } else if interfaces.contains_key(IFACE_SIMPLE)
                        && lock(&self.inner).modem_path.as_ref() == Some(&object)
                    {
                        self.enumerate();
                    }
                }
            }
            (Some(IFACE_OBJECT_MANAGER), Some("InterfacesRemoved")) => {
                if let Ok((object, interfaces)) =
                    body.deserialize::<(OwnedObjectPath, Vec<String>)>()
                {
                    if interfaces.iter().any(|i| i == IFACE_MODEM)
                        && lock(&self.inner).modem_path.as_ref() == Some(&object)
                    {
                        self.drop_modem();
                        self.emit(BackendEvent::Modem(ModemState::Absent));
                        self.emit(BackendEvent::Sim(SimState::Absent));
                        self.enumerate();
                    } else if interfaces.iter().any(|i| i == IFACE_BEARER)
                        && lock(&self.inner).modem_path.is_some()
                    {
                        let mut inner = lock(&self.inner);
                        if inner.owned_data_bearer.as_ref() == Some(&object) {
                            inner.owned_data_bearer = None;
                        }
                        drop(inner);
                        self.refresh_modem();
                    } else if interfaces.iter().any(|i| i == IFACE_SIMPLE)
                        && lock(&self.inner).modem_path.as_ref() == Some(&object)
                    {
                        self.enumerate();
                    }
                }
            }
            (Some(IFACE_MODEM), Some("StateChanged")) => self.refresh_modem(),
            (Some(IFACE_PROPERTIES), Some("PropertiesChanged")) => {
                let Ok((changed_iface, _changed, _invalidated)) =
                    body.deserialize::<(String, HashMap<String, OwnedValue>, Vec<String>)>()
                else {
                    return;
                };
                match changed_iface.as_str() {
                    IFACE_MODEM | IFACE_3GPP | IFACE_BEARER => self.refresh_modem(),
                    IFACE_SMS => {
                        if let Some(path) = path {
                            self.sms_properties_changed(&path);
                        }
                    }
                    IFACE_CALL => {
                        if let Some(path) = path
                            && let Ok(call) = self.call_proxy(&path)
                        {
                            let state = call.state().unwrap_or(0);
                            let reason =
                                u32::try_from(call.state_reason().unwrap_or(0)).unwrap_or(0);
                            self.call_state_changed(&path, state, reason);
                        }
                    }
                    _ => {}
                }
            }
            (Some(IFACE_VOICE), Some("CallAdded")) => {
                if let Ok(call) = body.deserialize::<OwnedObjectPath>() {
                    self.call_added(call);
                }
            }
            (Some(IFACE_VOICE), Some("CallDeleted")) => {
                if let Ok(call) = body.deserialize::<OwnedObjectPath>() {
                    self.call_deleted(&call);
                }
            }
            (Some(IFACE_CALL), Some("StateChanged")) => {
                if let Some(path) = path
                    && let Ok((_old, new, reason)) = body.deserialize::<(i32, i32, u32)>()
                {
                    self.call_state_changed(&path, new, reason);
                }
            }
            (Some(IFACE_MESSAGING), Some("Added")) => {
                if let Ok((sms, received)) = body.deserialize::<(OwnedObjectPath, bool)>() {
                    self.sms_added(sms, received);
                }
            }
            _ => {}
        }
    }

    fn tracked_call(
        &self,
        handle: &CallHandle,
    ) -> Result<(OwnedObjectPath, TrackedCall), BackendError> {
        let path = OwnedObjectPath::try_from(handle.0.as_str())
            .map_err(|_| BackendError::NotFound(handle.0.clone()))?;
        let inner = lock(&self.inner);
        let call = inner
            .calls
            .get(path.as_str())
            .cloned()
            .ok_or_else(|| BackendError::NotFound(handle.0.clone()))?;
        Ok((path, call))
    }
}

/// ModemManager reports numbers as dialled; normalise the common national
/// forms only when unambiguous (`00` international prefix).
fn normalize_number(raw: &str) -> String {
    let trimmed: String = raw
        .chars()
        .filter(|c| !c.is_whitespace() && *c != '-')
        .collect();
    if let Some(rest) = trimmed.strip_prefix("00") {
        format!("+{rest}")
    } else {
        trimmed
    }
}

impl ModemBackend for ModemManagerBackend {
    fn name(&self) -> &'static str {
        "modemmanager"
    }

    fn capabilities(&self) -> Capabilities {
        lock(&self.inner).snapshot.capabilities.clone()
    }

    fn snapshot(&self) -> BackendSnapshot {
        let mut snapshot = lock(&self.inner).snapshot.clone();
        snapshot.now_ms = self.now_ms();
        snapshot
    }

    fn subscribe(&self, sink: Sender<BackendEvent>) {
        lock(&self.inner).sinks.push(sink);
        // Stored inbound messages are events rather than snapshot state.  The
        // first subscription is therefore the earliest safe point to replay
        // them without losing them during `connect()`'s initial enumeration.
        self.replay_inbound_sms();
    }

    fn dial(&self, number: &E164) -> Result<CallHandle, BackendError> {
        let voice = self.voice_proxy()?;
        let snapshot = lock(&self.inner).snapshot.clone();
        if !snapshot.registration.is_registered() {
            return Err(BackendError::NoService);
        }
        let mut properties: HashMap<&str, Value<'_>> = HashMap::new();
        properties.insert("number", Value::from(number.as_str()));
        let path = voice.create_call(properties).map_err(bus_error)?;
        let call = self.call_proxy(&path)?;
        call.start().map_err(bus_error)?;
        self.call_added(path.clone());
        Ok(CallHandle(path.to_string()))
    }

    fn answer(&self, handle: &CallHandle) -> Result<(), BackendError> {
        let (path, call) = self.tracked_call(handle)?;
        if call.state != CallState::Ringing {
            return Err(BackendError::invalid_state(call.state, "answer"));
        }
        self.call_proxy(&path)?.accept().map_err(bus_error)
    }

    fn reject(&self, handle: &CallHandle) -> Result<(), BackendError> {
        let (path, call) = self.tracked_call(handle)?;
        if call.state != CallState::Ringing {
            return Err(BackendError::invalid_state(call.state, "reject"));
        }
        self.call_proxy(&path)?.hangup().map_err(bus_error)
    }

    fn hangup(&self, handle: &CallHandle) -> Result<(), BackendError> {
        let (path, call) = self.tracked_call(handle)?;
        if !call.state.is_live() {
            return Err(BackendError::invalid_state(call.state, "hangup"));
        }
        if let Some(c) = lock(&self.inner).calls.get_mut(path.as_str()) {
            c.local_hangup = true;
        }
        self.call_proxy(&path)?.hangup().map_err(bus_error)
    }

    /// ModemManager has no per-call hold; `HoldAndAccept` swaps active and
    /// held calls on the voice interface, which is the supported primitive.
    fn hold(&self, handle: &CallHandle) -> Result<(), BackendError> {
        let (_, call) = self.tracked_call(handle)?;
        if call.state != CallState::Active {
            return Err(BackendError::invalid_state(call.state, "hold"));
        }
        self.voice_proxy()?.hold_and_accept().map_err(bus_error)
    }

    fn resume(&self, handle: &CallHandle) -> Result<(), BackendError> {
        let (_, call) = self.tracked_call(handle)?;
        if call.state != CallState::Held {
            return Err(BackendError::invalid_state(call.state, "resume"));
        }
        self.voice_proxy()?.hold_and_accept().map_err(bus_error)
    }

    fn dtmf(&self, handle: &CallHandle, digit: Dtmf) -> Result<(), BackendError> {
        let (path, call) = self.tracked_call(handle)?;
        if call.state != CallState::Active {
            return Err(BackendError::invalid_state(call.state, "dtmf"));
        }
        self.call_proxy(&path)?
            .send_dtmf(&digit.as_char().to_string())
            .map_err(bus_error)
    }

    fn send_sms(&self, to: &E164, body: &str) -> Result<SmsHandle, BackendError> {
        let messaging = self.messaging_proxy()?;
        if !lock(&self.inner).snapshot.registration.is_registered() {
            return Err(BackendError::NoService);
        }
        let mut properties: HashMap<&str, Value<'_>> = HashMap::new();
        properties.insert("number", Value::from(to.as_str()));
        properties.insert("text", Value::from(body));
        properties.insert("delivery-report-request", Value::from(true));
        let path = messaging.create(properties).map_err(bus_error)?;
        lock(&self.inner).outgoing_sms.insert(path.to_string());
        self.sms_proxy(&path)?.send().map_err(bus_error)?;
        Ok(SmsHandle(path.to_string()))
    }

    fn connect_data(&self, profile: &DataProfile) -> Result<(), BackendError> {
        let snapshot = lock(&self.inner).snapshot.clone();
        match snapshot.sim {
            SimState::Absent => return Err(BackendError::NoSim),
            SimState::Locked { .. } | SimState::Blocked => {
                return Err(BackendError::SimLocked);
            }
            SimState::Failed { .. } => {
                return Err(BackendError::Backend("sim failed".to_owned()));
            }
            SimState::Ready => {}
        }
        if !snapshot.registration.is_registered() {
            return Err(BackendError::NoService);
        }
        if matches!(
            snapshot.data,
            DataBearer::Connected { .. } | DataBearer::Connecting
        ) {
            return Ok(());
        }
        let simple = self.simple_proxy()?;
        let requires_apn = lock(&self.inner).requires_apn;
        let configured_apn = configured_data_apn()?;
        let apn = select_data_apn(profile, configured_apn.as_deref(), requires_apn)?;
        let mut properties: HashMap<&str, Value<'_>> = HashMap::new();
        if let Some(apn) = apn.as_deref() {
            properties.insert("apn", Value::from(apn));
        }
        let bearer = simple.connect(properties).map_err(bus_error)?;
        lock(&self.inner).owned_data_bearer = Some(bearer);
        // The D-Bus signal normally supplies the transition, but refresh now
        // makes a synchronous caller observe a newly-created bearer without
        // waiting for the one-second fallback tick.
        self.refresh_modem();
        Ok(())
    }

    fn disconnect_data(&self) -> Result<(), BackendError> {
        let owned = lock(&self.inner).owned_data_bearer.clone();
        let Some(owned) = owned else {
            // Bearers created by another service (for example an IMS or
            // tethering PDN) are not ours to tear down.  This also gives the
            // operation its documented idempotent behaviour after a daemon
            // restart, where ownership is intentionally not reconstructed.
            self.refresh_modem();
            return Ok(());
        };
        let simple = self.simple_proxy()?;
        let modem = self.modem_proxy()?;
        let paths = modem.bearers().map_err(bus_error)?;
        if paths.iter().any(|path| path == &owned) {
            simple.disconnect(&owned).map_err(bus_error)?;
        }
        lock(&self.inner).owned_data_bearer = None;
        self.refresh_modem();
        Ok(())
    }

    fn set_radio_power(&self, power: RadioPower) -> Result<(), BackendError> {
        let modem = self.modem_proxy()?;
        match power {
            RadioPower::Off => {
                modem.enable(false).map_err(bus_error)?;
                modem
                    .set_power_state(mapping::power_state::LOW)
                    .map_err(bus_error)
            }
            RadioPower::On => {
                modem
                    .set_power_state(mapping::power_state::ON)
                    .map_err(bus_error)?;
                modem.enable(true).map_err(bus_error)
            }
        }
    }

    fn enter_pin(&self, pin: &str) -> Result<(), BackendError> {
        let modem = self.modem_proxy()?;
        let sim_path = modem.sim().map_err(bus_error)?;
        if sim_path.as_str() == "/" {
            return Err(BackendError::NoSim);
        }
        let sim = SimProxyBlocking::builder(&self.connection)
            .path(sim_path)
            .map_err(bus_error)?
            .build()
            .map_err(bus_error)?;
        sim.send_pin(pin).map_err(|e| {
            // ModemManager reports a wrong PIN as an error; the SIM state
            // (attempts left) follows through `StateChanged`.
            let text = e.to_string();
            if text.contains("IncorrectPassword") || text.contains("SimPuk") {
                BackendError::SimLocked
            } else {
                bus_error(e)
            }
        })
    }

    /// Delegated to the audio service when it exists; typed as unsupported
    /// here rather than imitated.
    fn set_audio_route(&self, _route: AudioRoute) -> Result<(), BackendError> {
        Err(BackendError::Unsupported(TelephonyFeature::AudioRoute))
    }
}

#[cfg(test)]
mod tests {
    use super::{is_samsung_sit_plugin, select_data_apn};
    use ferrix_telephony_api::DataProfile;

    #[test]
    fn samsung_sit_plugin_names_are_targeted() {
        assert!(is_samsung_sit_plugin(Some("samsung-sit")));
        assert!(is_samsung_sit_plugin(Some("samsung_sit")));
        assert!(!is_samsung_sit_plugin(Some("generic")));
        assert!(!is_samsung_sit_plugin(None));
    }

    #[test]
    fn explicit_apn_wins_over_target_fallback() {
        let profile = DataProfile {
            apn: Some("request.example".into()),
        };
        assert_eq!(
            select_data_apn(&profile, Some("target.example"), true).unwrap(),
            Some("request.example".into())
        );
    }

    #[test]
    fn target_fallback_supplies_samsung_sit_default_profile() {
        let profile = DataProfile::default();
        assert_eq!(
            select_data_apn(&profile, Some("target.example"), true).unwrap(),
            Some("target.example".into())
        );
        assert!(select_data_apn(&profile, None, true).is_err());
        assert!(select_data_apn(&profile, Some(""), true).is_err());
    }

    #[test]
    fn invalid_target_fallback_fails_closed_without_leaking_the_value() {
        let profile = DataProfile::default();
        let error = select_data_apn(&profile, Some("bad apn"), true).unwrap_err();
        assert_eq!(
            error.to_string(),
            "backend error: cellular data APN is invalid"
        );
        assert!(!error.to_string().contains("bad apn"));
    }

    #[test]
    fn generic_backend_can_still_use_its_carrier_default() {
        assert_eq!(
            select_data_apn(&DataProfile::default(), None, false).unwrap(),
            None
        );
    }
}
