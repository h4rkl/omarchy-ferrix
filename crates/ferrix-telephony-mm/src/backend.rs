/// Target bootstrap may provide a non-secret carrier APN through the board's
/// backend environment.  It is a fallback for clients that intentionally use
/// the default [`DataProfile`]; an explicit profile APN always wins.
const TELEPHONY_APN_ENV: &str = "FERRIX_TELEPHONY_APN";

/// `MM_PLUGIN_NAME` is normally the hyphenated module name, but accepting the
/// underscore spelling keeps this check robust across ModemManager package
/// builds that derive the name from the C symbol rather than the module file.
fn is_samsung_sit_plugin(name: Option<&str>) -> bool {
    matches!(name, Some("samsung-sit" | "samsung_sit"))
}

/// Select and validate the APN that will be sent to ModemManager.
///
/// This helper is deliberately independent of the process environment so the
/// precedence and fail-closed behaviour can be tested without mutating global
/// state.  An explicit request profile wins over the target's configured
/// fallback.  Empty fallback values mean "not configured"; an invalid
/// non-empty fallback is an error rather than silently falling back to a
/// carrier guess.  Samsung-SIT requires an APN, while generic ModemManager
/// plugins may still use their normal carrier profile selection.
fn select_data_apn(
    profile: &DataProfile,
    configured_apn: Option<&str>,
    requires_apn: bool,
) -> Result<Option<String>, BackendError> {
    let selected = match profile.apn.as_deref() {
        Some(apn) => Some(apn),
        None => configured_apn.filter(|apn| !apn.is_empty()),
    };
    let Some(apn) = selected else {
        return if requires_apn {
            Err(BackendError::backend(
                "Samsung SIT data calls require an explicit APN",
            ))
        } else {
            Ok(None)
        };
    };

    DataProfile {
        apn: Some(apn.to_owned()),
    }
    .validate()
    .map_err(|_| BackendError::backend("cellular data APN is invalid"))?;
    Ok(Some(apn.to_owned()))
}

fn configured_data_apn() -> Result<Option<String>, BackendError> {
    let Some(value) = std::env::var_os(TELEPHONY_APN_ENV) else {
        return Ok(None);
    };
    let value = value
        .to_str()
        .ok_or_else(|| BackendError::backend("configured cellular data APN is not valid UTF-8"))?;
    Ok((!value.is_empty()).then(|| value.to_owned()))
}

