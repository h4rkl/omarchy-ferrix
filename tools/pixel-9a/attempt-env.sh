#!/bin/sh
set -eu

# Prepare one device-free, source-bound static build attempt. This host
# workflow uses POSIX shell because its output is sourced into the existing
# shell-based native builder without requiring a Rust build on the host.
# Source the generated env.sh after tools/pixel-9a/env.sh.

root=$(CDPATH= cd -- "$(dirname -- "$0")/../.." && pwd)
out="$root/out/pixel-9a"

die() {
	printf 'FAIL pixel-9a-attempt-env: %s\n' "$*" >&2
	exit 2
}

[ "$#" -eq 2 ] || die 'usage: attempt-env.sh YYYYMMDDTHHMMSSZ out/pixel-9a/partition-capacities-static-<capture>.tsv'
attempt=$1
capacity=$2
printf '%s\n' "$attempt" | LC_ALL=C grep -Eq '^20[0-9]{6}T[0-9]{6}Z$' || die 'attempt ID must be a UTC timestamp YYYYMMDDTHHMMSSZ'
case "$capacity" in
	out/pixel-9a/partition-capacities-static-*.tsv) ;;
	*) die 'use an exact, named static capacity handoff under out/pixel-9a' ;;
esac
case "$capacity" in
	*'..'*|*[!A-Za-z0-9_./-]*) die 'capacity path has an unsafe component' ;;
esac
case "${capacity#out/pixel-9a/}" in
	*/*) die 'capacity handoff must be one named file, not a nested path' ;;
esac
[ -f "$root/$capacity" ] && [ ! -L "$root/$capacity" ] || die 'capacity handoff is missing or a symlink'
if command -v sha256sum >/dev/null 2>&1; then
	capacity_sha256=$(sha256sum "$root/$capacity" | awk '{ print $1 }')
else
	capacity_sha256=$(shasum -a 256 "$root/$capacity" | awk '{ print $1 }')
fi
command -v git >/dev/null 2>&1 || die 'git is required'
commit=$(git -C "$root" rev-parse --verify HEAD) || die 'cannot resolve reviewed source commit'
case "$commit" in
	*[!0-9a-f]*|'') die 'reviewed source commit is malformed' ;;
esac
[ "${#commit}" -eq 40 ] || die 'reviewed source commit must be a full Git SHA'
source_status=$(git -C "$root" status --porcelain --untracked-files=normal) || die 'cannot inspect builder checkout'
[ -z "$source_status" ] || die 'builder checkout must be clean at the reviewed commit'

kernel="out/pixel-9a/kernel-radio/tegu-wwan-$attempt"
product="out/pixel-9a/product/tegu-$attempt"
rootfs="out/pixel-9a/rootfs/tegu-$attempt"
inputs="out/pixel-9a/boot-inputs/tegu-wwan-$attempt"
images="out/pixel-9a/images/tegu-wwan-static-$attempt"
for path in "$kernel" "$product" "$rootfs" "$inputs" "$images"; do
	[ ! -e "$root/$path" ] && [ ! -L "$root/$path" ] || die "fresh output already exists: $path"
done
attempt_dir="$out/attempts/$attempt"
[ ! -e "$attempt_dir" ] && [ ! -L "$attempt_dir" ] || die 'attempt ID was already prepared'

mkdir -p "$attempt_dir"
env_file="$attempt_dir/env.sh"
{
	printf '# Pixel 9a static attempt %s; generated by tools/pixel-9a/attempt-env.sh\n' "$attempt"
	printf '# Source after tools/pixel-9a/env.sh from the repository root.\n'
	printf 'FERRIX_PIXEL9A_ATTEMPT_ID=%s\n' "$attempt"
	printf 'FERRIX_PIXEL9A_ATTEMPT_COMMIT=%s\n' "$commit"
	printf 'FERRIX_PIXEL9A_ATTEMPT_CAPACITY_SHA256=%s\n' "$capacity_sha256"
	printf 'FERRIX_PIXEL9A_RADIO_KERNEL_OUT=%s\n' "$kernel"
	printf 'FERRIX_PIXEL9A_RADIO_KERNEL_DIST=%s/dist\n' "$kernel"
	printf 'FERRIX_PIXEL9A_RADIO_KERNEL_MANIFEST=%s/build-manifest.tsv\n' "$kernel"
	printf 'FERRIX_PIXEL9A_PRODUCT_OUT=%s\n' "$product"
	printf 'FERRIX_PIXEL9A_PRODUCT_DIR=%s\n' "$product"
	printf 'FERRIX_PIXEL9A_ROOTFS_OUT=%s\n' "$rootfs"
	printf 'FERRIX_PIXEL9A_ROOTFS_MANIFEST=%s/manifest.tsv\n' "$rootfs"
	printf 'FERRIX_PIXEL9A_BOOT_INPUTS_OUT=%s\n' "$inputs"
	printf 'FERRIX_PIXEL9A_BOOT_INPUTS_MANIFEST=%s/manifest.tsv\n' "$inputs"
	printf 'FERRIX_PIXEL9A_STATIC_BOOT_OUT=%s\n' "$images"
	printf 'FERRIX_PIXEL9A_STATIC_PARTITION_SIZES=%s\n' "$capacity"
	printf 'export FERRIX_PIXEL9A_ATTEMPT_ID FERRIX_PIXEL9A_ATTEMPT_COMMIT FERRIX_PIXEL9A_ATTEMPT_CAPACITY_SHA256 FERRIX_PIXEL9A_RADIO_KERNEL_OUT FERRIX_PIXEL9A_RADIO_KERNEL_DIST FERRIX_PIXEL9A_RADIO_KERNEL_MANIFEST FERRIX_PIXEL9A_PRODUCT_OUT FERRIX_PIXEL9A_PRODUCT_DIR FERRIX_PIXEL9A_ROOTFS_OUT FERRIX_PIXEL9A_ROOTFS_MANIFEST FERRIX_PIXEL9A_BOOT_INPUTS_OUT FERRIX_PIXEL9A_BOOT_INPUTS_MANIFEST FERRIX_PIXEL9A_STATIC_BOOT_OUT FERRIX_PIXEL9A_STATIC_PARTITION_SIZES\n'
} > "$env_file"
printf 'attempt=%s\nsource_commit=%s\ncapacity=%s\ncapacity_sha256=%s\n' "$attempt" "$commit" "$capacity" "$capacity_sha256"
printf 'env_file=%s\n' "$env_file"
