#!/usr/bin/env python3
"""Merge stock media_codecs XMLs into one Waydroid overlay XML without secure codecs.

    waydroid-codec2-xml.py [--rank N] OUTPUT INPUT...

Reads the stock vendor `media_codecs*_c2.xml` inputs in order and writes one
`<MediaCodecs>` document holding their `<Decoders>`/`<Encoders>` entries:

  - `.secure` codecs and `secure-playback` features are dropped (the
    container has no protected-content path);
  - `<Include>` and `<Settings>` are dropped (the stock settings only
    describe secure-codec concurrency; includes name files the overlay does
    not carry);
  - with `--rank`, every codec definition (not `update="true"` entries)
    gets `rank="N"`, so Android's MediaCodecList orders the hardware codecs
    ahead of the container's ffmpeg and AOSP software codecs regardless of
    the stock component traits;
  - a codec defined twice is an error.

Offline; part of tools/pixel-9a/waydroid-codec2-overlay.sh.
"""

import argparse
import sys
import xml.etree.ElementTree as ET

SECTIONS = ("Decoders", "Encoders")


def die(message):
    print(f"FAIL pixel-9a-waydroid-codec2-xml: {message}", file=sys.stderr)
    sys.exit(1)


def is_secure(codec):
    return codec.get("name", "").endswith(".secure")


def strip_secure_features(codec):
    for parent in [codec, *codec.iter()]:
        for child in list(parent):
            if child.tag == "Feature" and child.get("name") == "secure-playback":
                parent.remove(child)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--rank", type=int)
    parser.add_argument("output")
    parser.add_argument("inputs", nargs="+")
    args = parser.parse_args()
    if args.rank is not None and args.rank < 0:
        die("--rank must not be negative")

    merged = {section: [] for section in SECTIONS}
    defined = set()
    for path in args.inputs:
        try:
            root = ET.parse(path).getroot()
        except (OSError, ET.ParseError) as error:
            die(f"cannot parse {path}: {error}")
        if root.tag != "MediaCodecs":
            die(f"{path} is not a <MediaCodecs> document")
        for child in root:
            if child.tag in ("Include", "Settings"):
                continue
            if child.tag not in SECTIONS:
                die(f"{path}: unexpected <{child.tag}>")
            for codec in child:
                if codec.tag != "MediaCodec" or "name" not in codec.attrib:
                    die(f"{path}: unexpected <{codec.tag}> in <{child.tag}>")
                if is_secure(codec):
                    continue
                strip_secure_features(codec)
                if codec.get("update") != "true":
                    if codec.get("name") in defined:
                        die(f"{path}: codec defined twice: {codec.get('name')}")
                    defined.add(codec.get("name"))
                    if args.rank is not None:
                        codec.set("rank", str(args.rank))
                merged[child.tag].append(codec)

    out = ET.Element("MediaCodecs")
    out.append(ET.Comment(" Generated by tools/pixel-9a/waydroid-codec2-xml.py from the stock "
                          "factory vendor image; secure codecs removed. "))
    for section in SECTIONS:
        if merged[section]:
            ET.SubElement(out, section).extend(merged[section])
    if not any(merged.values()):
        die("no codecs left after filtering")
    ET.indent(out, space="    ")
    with open(args.output, "wb") as handle:
        handle.write(b'<?xml version="1.0" encoding="utf-8" ?>\n')
        handle.write(ET.tostring(out, encoding="unicode").encode())
        handle.write(b"\n")


if __name__ == "__main__":
    main()
